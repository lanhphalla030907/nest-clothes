CREATE TABLE "administrative_locations" (
  "pcode" VARCHAR(8) NOT NULL,
  "parent_pcode" VARCHAR(8),
  "admin_level" SMALLINT NOT NULL,
  "name_en" VARCHAR(120) NOT NULL,
  "name_km" VARCHAR(120),
  "dataset_version" VARCHAR(10) NOT NULL,
  "cod_enabled_override" BOOLEAN,
  CONSTRAINT "administrative_locations_pkey" PRIMARY KEY ("pcode"),
  CONSTRAINT "administrative_locations_parent_fkey" FOREIGN KEY ("parent_pcode") REFERENCES "administrative_locations"("pcode") ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT "administrative_locations_source_identity_check" CHECK (
    ("admin_level" = 1 AND "pcode" ~ '^KH[0-9]{2}$' AND "parent_pcode" IS NULL) OR
    ("admin_level" = 2 AND "pcode" ~ '^KH[0-9]{4}$' AND "parent_pcode" = left("pcode", 4)) OR
    ("admin_level" = 3 AND "pcode" ~ '^KH[0-9]{6}$' AND "parent_pcode" = left("pcode", 6))
  )
);

CREATE INDEX "administrative_locations_parent_name_idx" ON "administrative_locations"("parent_pcode", "name_en");
CREATE INDEX "administrative_locations_level_name_idx" ON "administrative_locations"("admin_level", "name_en");

